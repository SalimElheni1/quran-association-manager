#!/usr/bin/env node
// Generates branch-schema.sql: the desktop database (src/db/schema.js + every migration in
// src/db/migrations, replayed the way src/db/db.js applies them) rewritten for PostgreSQL,
// with the rows the migrations seed. Run it again after adding a desktop migration:
//   node web/server/db/generate-branch-schema.js > web/server/db/branch-schema.sql
// and add the matching change for existing branches to branch-migrations/.

const { buildDesktopSqlite, tablesInDependencyOrder } = require('./desktopSchema');

const db = buildDesktopSqlite();
const tables = tablesInDependencyOrder(db);

const out = [
  '-- Generated by generate-branch-schema.js from the desktop schema and migrations. Do not edit.',
  '-- One copy of this schema exists per branch (schema branch_<id>); compat holds the SQLite',
  '-- functions the shared handlers use.',
  '',
];

for (const table of tables) {
  const sql = table.sql
    .replace(/--[^\n]*/g, '')
    .replace(/CREATE TABLE "(\w+)"/, 'CREATE TABLE $1')
    .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, 'SERIAL PRIMARY KEY')
    // Dates stay text (YYYY-MM-DD / YYYY-MM-DD HH:MM:SS) as on the desktop, so comparisons and
    // string functions behave the same.
    .replace(/\b(DATETIME|TIMESTAMP|DATE)\b(?=[\s,)])/g, 'TEXT')
    .replace(/\bDECIMAL\(10,2\)/gi, 'DOUBLE PRECISION')
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(/\bBOOLEAN DEFAULT FALSE\b/g, 'INTEGER DEFAULT 0')
    .replace(/DEFAULT CURRENT_TIMESTAMP/g, 'DEFAULT compat.sqlite_now()')
    .replace(/DEFAULT \(date\('now'\)\)/g, 'DEFAULT compat.sqlite_today()')
    // Byte-order comparison and sorting, as SQLite's BINARY collation, whatever the database
    // locale (a locale collation ignores the '-' and ':' in dates at the first level).
    .replace(/\bTEXT\b/g, 'TEXT COLLATE "C"')
    .replace(/\n\s*\n/g, '\n');
  out.push(sql.trim() + ';', '');
}

for (const ix of db
  .prepare("SELECT sql FROM sqlite_master WHERE type = 'index' AND sql IS NOT NULL ORDER BY name")
  .all()) {
  out.push(ix.sql.replace(/\s+/g, ' ').trim() + ';');
}
out.push('');

const TIMESTAMP_COLUMNS = new Set(['created_at', 'updated_at', 'applied_at']);
const literal = (value) => {
  if (value === null) return 'NULL';
  if (typeof value === 'number') return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
};
for (const { name } of tables) {
  const rows = db.prepare(`SELECT * FROM "${name}"`).all();
  if (!rows.length) continue;
  const cols = Object.keys(rows[0]);
  const values = rows.map(
    (row) =>
      `  (${cols.map((c) => (TIMESTAMP_COLUMNS.has(c) ? 'compat.sqlite_now()' : literal(row[c]))).join(', ')})`,
  );
  out.push(`INSERT INTO ${name} (${cols.join(', ')}) VALUES\n${values.join(',\n')};`, '');
}

out.push('SELECT compat.reset_sequences();', '');
process.stdout.write(out.join('\n'));
